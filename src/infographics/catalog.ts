export function figuresOf(postId: string): Figure[] {
  return figures[postId] ?? [];
}

export function findFigure(postId: string, id: string): { fig: Figure; eager: boolean } | undefined {
  const list = figuresOf(postId);
  const index = list.findIndex((fig) => fig.id === id);
  if (index < 0) return undefined;
  return { fig: list[index], eager: index === 0 };
}
